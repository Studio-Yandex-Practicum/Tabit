"""
Базовый модуль констант проекта.

Содержит фундаментальные константы, используемые во всех компонентах системы.
Организован по принципу "контейнеров констант" - вложенных классов, группирующих
константы по функциональному назначению.

Структура модуля:
- ColorCPrint: цвета для форматированного консольного вывода.
- Default: значения по умолчанию для системных настроек.
- Description: подробные описания API endpoints для документации.
- Directory: пути к директориям файловой системы.
- FakerConstants: настройки генератора тестовых данных.
- Length: базовый ограничения длины.
- MiscConstants: базовые технические константы.
- Summary: базовые краткие описания.
- TextError: базовые сообщения об ошибках.
- Title: базовые заголовки элементов.
- Validation: базовые правила валидации данных.

Принципы организации:
- Логическая группировка - каждая категория констант в своем классе.
- Неизменяемость - изменяемые классы помечены @dataclass(frozen=True).
- Типизация - все константы имеют явные type hints.
- Наследование - может использоваться для расширения в дочерних модулях.
- Документирование - каждый класс и значимая константа имеет docstring.

Пример использования:
- from config.constants.core import ConstantsBase
- page_size = ConstantsBase.Default.PAGE_SIZE
- media_dir = ConstantsBase.Directory.MEDIA
- error_msg = ConstantsBase.TextError.INVALID_TELEGRAM_USERNAME

Рекомендации:
- Для доступа к константам использовать полный путь через ConstantsBase.
- Новые константы добавлять в соответствующий тематический класс.
- Для проекто-специфичных констант создавать дочерние модули.
- Избегать дублирования констант между модулями.
"""

from dataclasses import dataclass


class ConstantsBase:
    """
    Базовый класс для хранения всех констант проекта.

    Содержит вложенные классы, группирующие константы по назначению.
    """

    @dataclass(frozen=True)
    class ColorCPrint:
        """
        Вложенный класс констант - цветов для вывода текста в консоли с помощью cprint.

        Класс реализован, как неизменяемый.
        """

    class Default:
        """
        Вложенный класс констант значений по умолчанию.

        Атрибуты:
        - PAGE_SIZE (int): Размер страницы по умолчанию.
        """

        PAGE_SIZE: int = 20

    class Description:
        """
        Вложенный класс констант для текстовых описаний.
        """

    class Directory:
        """
        Вложенный класс констант путей к директориям.

        Атрибуты:
        - LOGO (str): Название поддиректории для логотипов.
        - MEDIA (str): Название директории для медиафайлов.
        """

        LOGO: str = 'logo'
        MEDIA: str = 'media'

    class FakerConstants:
        """
        Вложенный класс констант - основных параметров генерации тестовых
        данных с помощью Faker.
        """

    class Length:
        """
        Вложенный класс констант, определяющих ограничения длины для различных полей.

        Атрибуты:
        - MAX_NAME (int): Максимальная длина имени.
        - MAX_SMALL_NAME (int): Максимальная длина короткого названия.
        """

        MAX_NAME: int = 100
        MAX_SMALL_NAME: int = 30

    @dataclass(frozen=True)
    class MiscConstants:
        """
        Вложенный класс разных общесистемных констант.

        Класс реализован, как неизменяемый.

        Атрибуты:
        - ONE (int): Числовая константа единицы для унификации.
        - ZERO (int): Числовая константа нуля для унификации.
        """

        ONE: int = 1
        ZERO: int = 0

    class Summary:
        """
        Вложенный класс констант кратких описаний.
        """

    class TextError:
        """
        Вложенный класс констант стандартных текстов ошибок.

        Атрибуты:
        - BASE64_FATAL (str): Шаблон сообщения об ошибке сохранения изображения.
        - BASE64_STARTSWITH (str): Префикс строк base64 для изображений.
        - BASE64_TYPE (str): Сообщение о неверном формате base64.
        - INVALID_TELEGRAM_USERNAME (str): Сообщение о занятом Telegram username.
        """

        BASE64_FATAL: str = 'Ошибка при сохранение картинки {image}: {error_class}: {error_text}'
        BASE64_STARTSWITH: str = 'data:image'
        BASE64_TYPE: str = (
            f'Переданный файл не является строкой начинающийся c {BASE64_STARTSWITH}'
        )
        INVALID_TELEGRAM_USERNAME: str = (
            'Пользователь с указанным Telegram username уже существует.'
        )

    class Title:
        """
        Вложенный класс констант - заголовков.
        """

    @dataclass(frozen=True)
    class Validation:
        """
        Вложенный класс констант для валидации данных.

        Класс реализован, как неизменяемый.
        """
