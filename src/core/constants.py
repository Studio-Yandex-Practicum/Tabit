"""
Модуль системных констант приложения.

Содержит ограничения длины полей, настройки логирования, различные технические константы,
тексты системных ошибок, правила валидации данных.
Организован в виде классов-контейнеров, сгруппированных по функциональному назначению.

Структура модуля:
- Length: ограничения длины.
- Logging: конфигурация системы логирования.
- MiscConstants: различные технические константы.
- TextError: стандартные сообщения об ошибках.
- Validation: правила валидации входных данных.

Импортируемые базовые классы:
- LengthBase: базовые ограничения длины.
- MiscConstantsBase: общие технические константы.
- TextErrorBase: стандартные тексты ошибок.
- ValidationBase: базовые правила валидации.

Важные особенности:
- Все классы наследуют соответствующие базовые классы констант.
- Дополнительные константы добавляются в дочерние классы.
- Все строковые константы должны быть типизированы.
- Константы логирования используют относительные пути.
- Сообщения об ошибках четко указывают на проблему.
- Регулярные выражения документируются с требованиями.

Примеры использования:
- from config.constants import Length, TextError
- max_name_length = Length.MAX_NAME
- error_msg = TextError.FORBIDDEN_ROLE_ADMIN
- password_pattern = Validation.PATTERN_PASSWORD
"""

from config.constants.src import LengthBase, MiscConstantsBase, TextErrorBase, ValidationBase


class Length(LengthBase):
    """
    Класс для хранения констант, связанных с допустимой длиной полей.

    Наследует все константы из LengthBase.

    Примеры:
    - MAX_NAME (int): максимальная длина имени.
    - MIN_PASSWORD (int): Минимальная длина пароля и т.д.
    """


class Logging:
    """
    Класс для хранения настроек логирования приложения.

    Атрибуты:
    - FAKE_DB_DATA_LOG_FILE (str): Путь к файлу логов для фейковых данных БД.
    - LOG_FILE (str): Путь к основному файлу логов.
    - LOG_RETENTION (str): Срок хранения логов (например, '7 days').
    - LOG_ROTATION (str): Периодичность ротации логов (например, '1 day').
    """

    FAKE_DB_DATA_LOG_FILE: str = 'logs/fake_db_data.log'
    LOG_FILE: str = 'logs/tabit.log'
    LOG_RETENTION: str = '7 days'
    LOG_ROTATION: str = '1 day'


class MiscConstants(MiscConstantsBase):
    """
    Различные константы приложения.

    Содержит константы, которые не относятся к другим конкретным категориям.

    Наследует все константы из MiscConstantsBase.

    Примеры:
    - BASE_DIR (Path): Корневая директория проекта.
    - ZERO (int): Числовая константа нуля для унификации и т.д.
    """


class TextError(TextErrorBase):
    """
    Класс для хранения стандартных текстов ошибок приложения.

    Наследует все константы из TextErrorBase.

    Атрибуты:
    - FORBIDDEN_ROLE_MODERATOR (str): Сообщение об ошибке доступа для действий,
      требующих прав модератора компании.
    """

    FORBIDDEN_ROLE_MODERATOR: str = 'Доступно только модераторам компаний'


class Validation(ValidationBase):
    """
    Класс для хранения правил валидации данных.

    Наследует все константы из ValidationBase.

    Атрибуты:
    - PATTERN_PASSWORD (str): Регулярное выражение для проверки сложности пароля.
      - Требования:
        1) Минимум одна строчная буква
        2) Минимум одна заглавная буква
        3) Минимум одна цифра
        4) Только латинские буквы и цифры
        5) Минимальная длина из Length.MIN_PASSWORD
    """

    PATTERN_PASSWORD: str = (
        rf'^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)[A-Za-z\d]{{{Length.MIN_PASSWORD},}}$'
    )
